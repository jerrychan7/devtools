/**
 * Assembles the CSS lexer (lexer.ts) and the outline (outline.ts), written apart, into one
 * WebAssembly module. `node build.ts` writes ../css-wasm-bytes.ts; css-lexer-wasm.test.ts fails
 * until it is run again after a change to either.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as A from './assembler.ts';
import { lexerInto } from './lexer.ts';
import { outlineInto } from './outline.ts';

export function build(): Uint8Array {
  const m = new A.Module(3);
  lexerInto(m);
  outlineInto(m);
  return m.encode();
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const bytes = build();
  const out = fileURLToPath(new URL('../css-wasm-bytes.ts', import.meta.url));
  writeFileSync(
    out,
    `// Generated by wasm-gen/build.ts (\`node build.ts\` there): do not edit.\n` +
      `/** The CSS lexer and outline's WebAssembly module, ${bytes.length} bytes, in base64. */\n` +
      `export const CSS_WASM =\n  '${Buffer.from(bytes).toString('base64')}';\n`
  );
  console.log(`${bytes.length} bytes written to ${out}`);
}
